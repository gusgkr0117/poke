#ifndef INKE_MIXED_CHAIN_H
#define INKE_MIXED_CHAIN_H
#include "theta_isogenies.h"
#include "theta_isogeny3.h"

typedef struct {
    theta_couple_curve_t domain,codomain;
    theta_gluing_t glue;
    theta_isogeny_t *two;
    inke_theta_isogeny3 *three;
    theta_splitting_t splitting;
    int *product_prefix,prefix_length;
    int len2,len3,ready,failed_stage;
    unsigned long kernel_doublings,kernel_triplings;
} inke_product_chain;

void inke_chain_init(inke_product_chain *chain);
void inke_chain_clear(inke_product_chain *chain);
/* K2 generators have order 2^(len2+2). K3 generators have order 3^len3.
 * Their kernels must be maximal isotropic. Unsupported charts return 0.
 * No sampling or replacement of an ideal takes place in this module. */
int inke_chain_compute(inke_product_chain *out,
    const theta_couple_curve_t *domain,
    const theta_couple_jac_point_t K2[2], int len2,
    const theta_couple_jac_point_t K3[2], int len3);
/* The kernel is generated by [4]lifted[0],[4]lifted[1]. Return the image
 * of lifted[0] already propagated during the chain construction. */
int inke_chain_compute_with_lift(inke_product_chain *out,
    const theta_couple_curve_t *domain,
    const theta_couple_jac_point_t lifted[2],int len2,theta_couple_point_t *lift_image);
/* A pure 2-primary quotient using generators of exact order 2^len2. */
int inke_chain_compute_exact(inke_product_chain *out,
    const theta_couple_curve_t *domain,
    const theta_couple_jac_point_t K2[2], int len2);
/* Independent sequential traversal retained for strategy regression tests.
 * It computes the same kernels, without the balanced traversal. */
int inke_chain_compute_reference(inke_product_chain *out,
    const theta_couple_curve_t *domain,
    const theta_couple_jac_point_t K2[2], int len2,
    const theta_couple_jac_point_t K3[2], int len3);
int inke_chain_compute_exact_reference(inke_product_chain *out,
    const theta_couple_curve_t *domain,
    const theta_couple_jac_point_t K2[2], int len2);
int inke_chain_eval(theta_couple_point_t *out,
    const inke_product_chain *chain, const theta_couple_jac_point_t *P);
int inke_chain_eval_one(theta_couple_point_t *out,
    const inke_product_chain *chain, const ec_point_t *P, int side);
#endif
