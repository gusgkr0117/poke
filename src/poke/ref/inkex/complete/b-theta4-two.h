#ifndef INKE_RESEARCH_THETA4_TWO_H
#define INKE_RESEARCH_THETA4_TWO_H
#include "b-theta4.h"

/* A marked degree-(2,...,2) quotient after the kernel has been moved to
 * alpha=2e_i,beta=0. Only shifts of weight at most two are retained.
 * Higher shifts use bounded memoized recomputation, never 2^g vectors. */
typedef struct {
  b_theta4_ctx *source;
  fq_struct **kernel_lift;
  fq_struct *target_null;
  unsigned trace_seed;
  uint64_t init_three_way_calls,last_evaluate_three_way_calls;
} b_theta4_two_ctx;

/* basis[i] is an arbitrary affine lift of T_i with 2T_i=(alpha=e_i,beta=0).
 * pairs[i*g+j] (i<j) is an arbitrary lift of T_i+T_j. The G1 generated by
 * the T_i must be isotropic and symmetric-compatible (DL Algorithm3).
 * Returns the good_basis2/good_coset2 status on failure, 1 on success.
 * On failure the context is empty. No implicit change of marking occurs. */
int b_theta4_two_init(b_theta4_two_ctx *Q,b_theta4_ctx *source,
    const fq_struct *const *basis,const fq_struct *const *pairs,
    const fq_t zeta);
void b_theta4_two_clear(b_theta4_two_ctx *Q);

/* Input shifted[i] is any affine lift of x+T_i, matching the actual group
 * points supplied at initialization. All coset scaling is tracked squared:
 * no roots or extension fields are needed in this evaluation routine.
 * out is unchanged on failure. */
int b_theta4_two_evaluate(fq_struct *out,const fq_struct *x,
    const fq_struct *const *shifted,const fq_t zeta,b_theta4_two_ctx *Q);
/* Complete evaluator from the current point alone. Computes the g needed
 * translates by projective level-four addition; no recursive queries to an
 * earlier isogeny prefix occur. */
int b_theta4_two_evaluate_point(fq_struct *out,const fq_struct *x,
    const fq_t zeta,b_theta4_two_ctx *Q);
#endif
